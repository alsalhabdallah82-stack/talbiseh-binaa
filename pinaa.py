import math

print("=== 🏗️ حاسبة مواد البناء والتكلفة التقديرية ===")

try:
    # 1. إدخال أبعاد البناء من المستخدم
    length = float(input("أدخل طول الجدار (أو محيط الغرفة) بالمتر: "))
    height = float(input("أدخل ارتفاع الجدار بالمتر (مثلاً 3): "))
    
    # حساب المساحة الكلية
    area = length * height
    print(f"\n📏 المساحة الإجمالية للبناء هي: {area:.2f} متر مربع.")

    # 2. المعادلات الهندسية القياسية للمتر المربع الواحد
    # المتر المربع يحتاج وسطياً 12.5 بلوكة (قياس 20×40 سم) + 5% نسبة هدر وكسر
    blocks_needed = math.ceil((area * 12.5) * 1.05)
    
    # كل 100 بلوكة تحتاج وسطياً 1.5 كيس إسمنت (للبناء + التلييس/الزريقة من الوجهين)
    cement_bags = math.ceil((blocks_needed / 100) * 1.5)
    
    # كل كيس إسمنت يحتاج وسطياً 0.15 متر مكعب من الرمل
    sand_m3 = round(cement_bags * 0.15, 2)

    print("\n--- 📦 المواد المطلوبة بدقة (مع حساب نسبة الهدر) ---")
    print(f"🧱 عدد البلوك المطلوب: {blocks_needed} بلوكة")
    print(f"🛍️ عدد أكياس الإسمنت: {cement_bags} كيس (وزن 50 كغ)")
    print(f"🏜️ كمية الرمل المطلوبة: {sand_m3} متر مكعب")

    # 3. حساب التكلفة المالية (اختياري)
    calc_cost = input("\nهل تريد حساب التكلفة المالية التقريبية؟ (نعم / لا): ").strip()
    
    if calc_cost == "نعم":
        block_price = float(input("كم سعر البلوكة الواحدة حالياً؟ "))
        cement_price = float(input("كم سعر كيس الإسمنت الواحد حالياً؟ "))
        sand_price = float(input("كم سعر المتر المكعب من الرمل حالياً؟ "))
        
        total_cost = (blocks_needed * block_price) + (cement_bags * cement_price) + (sand_m3 * sand_price)
        print(f"\n💰 التكلفة الإجمالية التقديرية للمواد هي: {total_cost:,.0f} ليرة سورية")
        print("ملاحظة: السعر لا يشمل أجور المعلم والعمال.")

except ValueError:
    print("❌ خطأ: يرجى إدخال أرقام صحيحة فقط (استخدم النقطة للكسور مثل 3.5).")
  
